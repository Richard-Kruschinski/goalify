import 'package:flutter/material.dart';

/// Custom gym icons (Push / Pull / Cardio / Muscle / Barbell / Lungs / Back /
/// Torso / Legs / Abs / Shoulders)
/// drawn with CustomPainter.
/// They are stored in the day-icon map using negative sentinel codes,
/// which can never collide with Material IconData codePoints.
class GymIcons {
  static const int push = -1;
  static const int pull = -2;
  static const int cardio = -3;
  static const int muscle = -4;
  static const int barbell = -5;
  static const int lungs = -6;
  static const int back = -7;
  static const int torso = -8;
  static const int legs = -9;
  static const int abs = -10;
  static const int shoulders = -11;

  static const List<int> all = [
    push,
    pull,
    cardio,
    muscle,
    barbell,
    lungs,
    back,
    torso,
    legs,
    abs,
    shoulders,
  ];

  static bool isCustom(int? code) => code != null && code < 0;

  static Widget icon(int code, {double size = 24, required Color color}) {
    return SizedBox(
      width: size,
      height: size,
      child: Center(
        child: CustomPaint(
          size: Size.square(size),
          painter: _GymIconPainter(code: code, color: color),
        ),
      ),
    );
  }
}

class _GymIconPainter extends CustomPainter {
  const _GymIconPainter({required this.code, required this.color});

  final int code;
  final Color color;

  @override
  void paint(Canvas canvas, Size size) {
    // All shapes are defined on a 64x64 grid.
    canvas.scale(size.shortestSide / 64);

    final stroke = Paint()
      ..color = color
      ..style = PaintingStyle.stroke
      ..strokeWidth = 5
      ..strokeCap = StrokeCap.round
      ..strokeJoin = StrokeJoin.round;
    final fill = Paint()..color = color;

    switch (code) {
      case GymIcons.push:
        _paintPush(canvas, stroke, fill);
        break;
      case GymIcons.pull:
        _paintPull(canvas, stroke, fill);
        break;
      case GymIcons.cardio:
        _paintCardio(canvas, stroke);
        break;
      case GymIcons.muscle:
        _paintMuscle(canvas, fill);
        break;
      case GymIcons.barbell:
        _paintBarbell(canvas, fill);
        break;
      case GymIcons.lungs:
        _paintLungs(canvas, fill);
        break;
      case GymIcons.back:
        _paintBack(canvas, fill);
        break;
      case GymIcons.torso:
        _paintTorso(canvas, fill);
        break;
      case GymIcons.legs:
        _paintLegs(canvas, fill);
        break;
      case GymIcons.abs:
        _paintAbs(canvas, fill);
        break;
      case GymIcons.shoulders:
        _paintShoulders(canvas, fill);
        break;
    }
  }

  // Bench bar at the bottom, arrow pressing up and away.
